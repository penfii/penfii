// Writes packages/contracts/src/generated.ts, the TypeScript types of packages/contracts/openapi.json.
//   node scripts/generate-types.mjs           write the file
//   node scripts/generate-types.mjs --check   fail when the file is not what the spec produces (used by `make check`)
// The spec is parsed strictly: a key written twice in one object (which JSON.parse silently resolves to the last
// one) fails the run, as it once hid a whole operation.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import openapiTS, { astToString } from 'openapi-typescript'

const root = join(dirname(fileURLToPath(import.meta.url)), '..', 'packages', 'contracts')
const spec = join(root, 'openapi.json')
const target = join(root, 'src', 'generated.ts')
const banner = '/**\n * Generated by `npm run contract:types` from openapi.json. Do not edit by hand.\n */\n\n'

const ast = await openapiTS(new URL(`file://${spec}`))
const text = banner + astToString(ast)

if (process.argv.includes('--check')) {
  let current = ''
  try {
    current = readFileSync(target, 'utf8')
  } catch {
    // Missing counts as different.
  }
  if (current !== text) {
    console.error('packages/contracts/src/generated.ts is out of date with openapi.json. Run: npm run contract:types')
    process.exit(1)
  }
  console.log('packages/contracts/src/generated.ts matches openapi.json.')
} else {
  writeFileSync(target, text)
  console.log('Wrote packages/contracts/src/generated.ts.')
}
