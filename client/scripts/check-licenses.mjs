// Fails when a package resolved in package-lock.json has a licence outside the set compatible with GPL-3.0-only.
// Engineering compatibility check, not legal advice. Reads the lock file only, so it needs no node_modules.
import { readFileSync } from 'node:fs';

const ALLOWED = new Set([
  'MIT', 'MIT-0', 'Apache-2.0', 'BSD-2-Clause', 'BSD-3-Clause', 'ISC', 'Zlib', '0BSD', 'CC0-1.0', 'Unlicense',
  'MPL-2.0', 'BlueOak-1.0.0', 'Python-2.0', 'CC-BY-4.0', 'GPL-3.0-only', 'GPL-3.0-or-later', 'LGPL-3.0-or-later',
]);
// Packages whose licence field is missing or non-SPDX, reviewed by hand. Each entry needs a reason.
const REVIEWED = new Map([]);

function ok(expr) {
  const tokens = expr.replace(/[()]/g, (c) => ` ${c} `).split(/\s+/).filter(Boolean);
  let pos = 0;
  const atom = () => {
    const t = tokens[pos++];
    if (t === '(') { const v = or(); pos++; return v; }
    return ALLOWED.has(t.replace(/\+$/, '')) || ALLOWED.has(t);
  };
  const and = () => { let v = atom(); while (tokens[pos] === 'AND') { pos++; v = atom() && v; } return v; };
  const or = () => { let v = and(); while (tokens[pos] === 'OR') { pos++; v = and() || v; } return v; };
  return or();
}

const lock = JSON.parse(readFileSync(new URL('../package-lock.json', import.meta.url), 'utf8'))
if (process.argv.includes('--notices')) {
  const rows = []
  for (const [path, pkg] of Object.entries(lock.packages)) {
    if (path === '' || !path.includes('node_modules') || pkg.link) continue
    const name = path.slice(path.lastIndexOf('node_modules/') + 'node_modules/'.length)
    rows.push([name, pkg.version, (typeof pkg.license === 'string' ? pkg.license : pkg.license?.type) ?? '?'])
  }
  rows.sort((a, b) => (a[0] + a[1]).localeCompare(b[0] + b[1]))
  const out = ['# Third-party notices (npm)', '', 'Generated by `make notices` from `package-lock.json`. penfii itself is GPL-3.0-only (see `LICENSE` at the repository root).', '', '| Package | Version | License |', '|---|---|---|', ...rows.map(([n, v, l]) => `| ${n} | ${v} | ${l} |`)]
  process.stdout.write(out.join('\n') + '\n')
  process.exit(0)
};
const counts = new Map();
const bad = [];
for (const [path, pkg] of Object.entries(lock.packages)) {
  if (path === '' || !path.includes('node_modules') || pkg.link) continue; // workspace packages are ours
  const name = path.slice(path.lastIndexOf('node_modules/') + 'node_modules/'.length);
  const lic = typeof pkg.license === 'string' ? pkg.license : pkg.license?.type;
  if (REVIEWED.has(name)) continue;
  if (!lic) { bad.push(`${name}@${pkg.version}: no license field`); continue; }
  counts.set(lic, (counts.get(lic) ?? 0) + 1);
  if (!ok(lic)) bad.push(`${name}@${pkg.version}: ${lic}`);
}
for (const [lic, n] of [...counts].sort()) console.log(String(n).padStart(4), ' ', lic);
if (bad.length) { console.error('\nlicences outside the allowed set:\n' + bad.join('\n')); process.exit(1); }
