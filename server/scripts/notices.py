#!/usr/bin/env python3
"""Print THIRD-PARTY-NOTICES.md: every third-party crate in Cargo.lock with its version, licence and source.

`make notices` writes the file and `make notices-check` fails when it is out of date. The licence policy itself is
`[licenses]` in deny.toml (`make licenses`).
"""
import json
import subprocess
import sys

meta = json.loads(subprocess.check_output(["cargo", "metadata", "--format-version", "1", "--locked"]))
rows = sorted(
    (p["name"], p["version"], p.get("license") or "?", p.get("repository") or "")
    for p in meta["packages"]
    if p.get("source") is not None
)
lines = [
    "# Third-party notices (Rust)",
    "",
    "Generated by `make notices` from `Cargo.lock`. penfii itself is GPL-3.0-only (see `LICENSE` at the repository root).",
    "",
    "| Crate | Version | License | Source |",
    "|---|---|---|---|",
]
lines += [f"| {n} | {v} | {lic} | {repo} |" for n, v, lic, repo in rows]
sys.stdout.write("\n".join(lines) + "\n")
