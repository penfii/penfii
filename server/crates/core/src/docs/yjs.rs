    #[test]
    fn seed_then_materialize_is_the_canonical_content() {
        let (canonical, _) = content::sanitize(&rich(), usize::MAX).unwrap();
        let bytes = seed(&rich()).unwrap();
        let (back, found) = materialize_update(&bytes, usize::MAX).unwrap();
        assert_eq!(back, canonical);
        assert_eq!(found.files.len(), 1);
        assert_eq!(found.targets.len(), 2);
    }

    #[test]
    fn unknown_structure_is_refused_by_name() {
        let doc = seed_doc(&rich()).unwrap();
        let fragment = doc.get_or_insert_xml_fragment(FRAGMENT);
        {
            let mut txn = doc.transact_mut();
            let group = match fragment.get(&txn, 0) {
                Some(XmlOut::Element(group)) => group,
                other => panic!("{other:?}"),
            };
            let container = group.push_back(&mut txn, XmlElementPrelim::empty("blockContainer"));
            container.insert_attribute(&mut txn, "id", "evil".to_owned());
            container.push_back(&mut txn, XmlElementPrelim::empty("toggleListItem"));
        }
        let error = materialize(&doc, usize::MAX).unwrap_err();
        assert!(error.0.contains("toggleListItem"), "{error}");
    }

    #[test]
    fn an_empty_fragment_materializes_as_one_empty_paragraph() {
        let doc = Doc::new();
        let (content, _) = materialize(&doc, usize::MAX).unwrap();
        assert_eq!(content["blocks"].as_array().unwrap().len(), 1);
        assert_eq!(content["blocks"][0]["type"], "paragraph");
    }

    #[test]
    fn concurrent_edits_merge_and_materialize_the_same_everywhere() {
        let seed_bytes = seed(&content::empty()).unwrap();
        let a = doc_from_update(&seed_bytes).unwrap();
        let b = doc_from_update(&seed_bytes).unwrap();
        // Both insert into the same paragraph at the same place.
        let insert = |doc: &Doc, text: &str| {
            let fragment = doc.get_or_insert_xml_fragment(FRAGMENT);
            let mut txn = doc.transact_mut();
            let group = match fragment.get(&txn, 0) {
                Some(XmlOut::Element(g)) => g,
                _ => panic!(),
            };
            let container = match group.get(&txn, 0) {
                Some(XmlOut::Element(c)) => c,
                _ => panic!(),
            };
            let node = match container.get(&txn, 0) {
                Some(XmlOut::Element(n)) => n,
                _ => panic!(),
            };
            let text_node = node.push_back(&mut txn, XmlTextPrelim::new(text));
            let _ = text_node;
        };
        insert(&a, "안녕 ");
        insert(&b, "world");
        let ua =
            yrs::ReadTxn::encode_state_as_update_v1(&a.transact(), &yrs::StateVector::default());
        let ub =
            yrs::ReadTxn::encode_state_as_update_v1(&b.transact(), &yrs::StateVector::default());
        a.transact_mut()
            .apply_update(Update::decode_v1(&ub).unwrap())
            .unwrap();
        b.transact_mut()
            .apply_update(Update::decode_v1(&ua).unwrap())
            .unwrap();
        let (ca, _) = materialize(&a, usize::MAX).unwrap();
        let (cb, _) = materialize(&b, usize::MAX).unwrap();
        assert_eq!(ca, cb, "both replicas converge to the same JSON");
        let text = content::plain_text(&ca, 1 << 20).0;
        assert!(text.contains("안녕") && text.contains("world"), "{text}");
    }

    // Golden fixtures. The file is generated by BlockNote (client side) and by the
    // seeder below; see the header of client/packages/client/src/modules/docs/golden.test.ts for the update steps.
    mod golden {
        use super::*;
        use base64::Engine;

        const FILE: &str = include_str!("../../fixtures/doc-golden.json");

        fn b64() -> base64::engine::GeneralPurpose {
            base64::engine::general_purpose::STANDARD
        }

        fn wrap(blocks: &Value) -> Value {
            json!({"schema": content::SCHEMA, "version": content::VERSION, "blocks": blocks})
        }

        #[test]
        fn blocknote_bytes_materialize_to_what_blocknote_reads_from_them() {
            let file: Value = serde_json::from_str(FILE).unwrap();
            let fixtures = file["fixtures"].as_array().unwrap();
            assert!(fixtures.len() >= 10, "the fixture file is empty");
            for f in fixtures {
                let name = f["name"].as_str().unwrap();
                let bytes = b64().decode(f["update_js"].as_str().unwrap()).unwrap();
                let (ours, _) = materialize_update(&bytes, usize::MAX)
                    .unwrap_or_else(|e| panic!("{name}: {e}"));
                let (theirs, _) = content::sanitize(&wrap(&f["bn_blocks"]), usize::MAX)
                    .unwrap_or_else(|e| panic!("{name}: {e}"));
                assert_eq!(
                    ours, theirs,
                    "{name}: Rust and BlockNote read the same bytes differently"
                );
                // The JS input is canonical already: the round trip changes nothing.
                let (input, _) = content::sanitize(&wrap(&f["input"]), usize::MAX).unwrap();
                assert_eq!(ours, input, "{name}: JS bytes lost or changed content");
            }
        }

        #[test]
        fn the_rust_seed_round_trips_and_the_recorded_seed_still_reads_back() {
            let mut file: Value = serde_json::from_str(FILE).unwrap();
            let update = std::env::var("UPDATE_GOLDEN").ok().as_deref() == Some("1");
            for f in file["fixtures"].as_array_mut().unwrap() {
                let name = f["name"].as_str().unwrap().to_owned();
                let (input, _) = content::sanitize(&wrap(&f["input"]), usize::MAX).unwrap();
                let bytes = seed(&input).unwrap();
                let (back, _) = materialize_update(&bytes, usize::MAX).unwrap();
                assert_eq!(back, input, "{name}: seed then materialize");
                if update {
                    f["update_rust"] = json!(b64().encode(&bytes));
                } else {
                    // The recorded seed (made by an earlier run) must still read back as the input:
                    // the bytes themselves may differ between runs, their meaning may not.
                    let recorded = b64().decode(f["update_rust"].as_str().unwrap()).unwrap();
                    let (again, _) = materialize_update(&recorded, usize::MAX).unwrap();
                    assert_eq!(
                        again, input,
                        "{name}: the recorded Rust seed no longer reads back"
                    );
                }
            }
            if update {
                let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
                    .join("fixtures/doc-golden.json");
                std::fs::write(path, serde_json::to_string_pretty(&file).unwrap() + "\n").unwrap();
            }
        }
    }
